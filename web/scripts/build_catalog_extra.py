"""content/catalog_extra.json (+ distances from content/passage_maps.json) → supabase/seed_extra.sql and the offline
fallback in content/catalog.json. Re-run after editing the extra content, then apply seed_extra.sql to the database."""
import json, os
WEB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = json.load(open(f'{WEB}/content/catalog_extra.json'))
maps = json.load(open(f'{WEB}/content/passage_maps.json'))
cmaps = json.load(open(f'{WEB}/content/course_maps.json'))
gal = lambda xs: [{'photo_id': x[1], 'shape': x[2], 'caption': x[3]} for x in xs]
skl = lambda xs: [{'icon': i, 'title': t, 'items': it} for i, t, it in xs]
rte = lambda xs: [{'name': s[0], 'lon': s[1], 'lat': s[2], 'note': s[3]} for s in xs]
q = lambda s: "'" + s.replace("'", "''") + "'"
arr = lambda xs: 'array[' + ','.join(q(x) for x in xs) + ']::text[]' if xs else "'{}'::text[]"
js = lambda v: q(json.dumps(v, ensure_ascii=False)) + '::jsonb'
steps = lambda xs: [{'title': t, 'text': x} for t, x in xs]

P = src['passages']
legs = {}
for key, leg in P['legs'].items():
    stops = [{'name': s[0], 'lon': s[1], 'lat': s[2], 'note': s[3] if len(s) > 3 else P['ports'].get(s[0], '')} for s in leg['stops']]
    legs[key] = {
        'leg': key, 'summary': leg['summary'], 'about': leg['about'], 'stops': stops, 'distance_nm': maps[key]['nm'],
        'program': steps(P['program']),
        'requirements': P['requirements'] + P['extra_requirements'].get(key, []),
        'bring': P['bring'] + P['extra_bring'].get(key, []),
        'gallery': gal(leg.get('gallery', [])),
    }

out = ['-- Course programmes and passage routes (generated by scripts/build_catalog_extra.py)', 'begin;']
for slug, c in src['courses'].items():
    out.append(f"update public.courses set about = {arr(c['about'])}, program = {js(steps(c['program']))}, requirements = {arr(c['requirements'])}, bring = {arr(c['bring'])}, "
               f"included = {arr(c.get('included', []))}, not_included = {arr(c.get('not_included', []))}, after = {js(steps(c.get('after', [])))}, "
               f"gallery = {js(gal(c.get('gallery', [])))}, skills = {js(skl(c.get('skills', [])))}, route = {js(rte(c.get('route', [])))}, route_nm = {cmaps[slug]['nm'] if slug in cmaps else 'null'} where slug = {q(slug)};")
out.append('insert into public.passage_legs (leg, summary, about, stops, distance_nm, program, requirements, bring, gallery) values')
out.append(',\n'.join(f"  ({q(l['leg'])}, {q(l['summary'])}, {arr(l['about'])}, {js(l['stops'])}, {l['distance_nm']}, {js(l['program'])}, {arr(l['requirements'])}, {arr(l['bring'])}, {js(l['gallery'])})" for l in legs.values()))
out.append('on conflict (leg) do update set summary = excluded.summary, about = excluded.about, stops = excluded.stops, distance_nm = excluded.distance_nm, program = excluded.program, requirements = excluded.requirements, bring = excluded.bring, gallery = excluded.gallery;')
out.append('commit;')
open(f'{WEB}/supabase/seed_extra.sql', 'w').write('\n'.join(out) + '\n')

cat = json.load(open(f'{WEB}/content/catalog.json'))
for c in cat['courses']:
    e = src['courses'].get(c['slug'])
    c.update({'about': e['about'], 'program': steps(e['program']), 'requirements': e['requirements'], 'bring': e['bring'],
              'included': e.get('included', []), 'not_included': e.get('not_included', []), 'after': steps(e.get('after', [])),
              'gallery': gal(e.get('gallery', [])), 'skills': skl(e.get('skills', [])), 'route': rte(e.get('route', [])), 'route_nm': cmaps.get(c['slug'], {}).get('nm')}
             if e else {'about': [], 'program': [], 'bring': [], 'included': [], 'not_included': [], 'after': [], 'gallery': [], 'skills': [], 'route': [], 'route_nm': None})
cat['passage_legs'] = list(legs.values())
json.dump(cat, open(f'{WEB}/content/catalog.json', 'w'), ensure_ascii=False, indent=1)
print('seed_extra.sql and catalog.json written:', len(src['courses']), 'courses,', len(legs), 'legs')
